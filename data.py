# ---------------------------------------------------------------------------
# 状态结算（硬编码规则）
# ---------------------------------------------------------------------------

def apply_delta(affection: int, delta) -> int:
    """LLM 只提供 delta，此处按硬编码边界结算。"""
    try:
        delta = int(delta)
    except (TypeError, ValueError):
        return max(0, min(100, affection))
    delta = max(-AFFECTION_MAX_DELTA, min(AFFECTION_MAX_DELTA, delta))
    return max(0, min(100, affection + delta))
